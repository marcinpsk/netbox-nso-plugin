"""Check the canonical generator's integrity metadata without importing its output."""

import hashlib
import re

_HEADER = re.compile(
    rb"# BEGIN REFUSAL PROTOCOL INTEGRITY\n"
    rb"# GENERATED by tools/gen_refusal_protocol.py from protocols/refusal/\. Do not edit: regenerate\.\n"
    rb"# source-sha256: ([0-9a-f]{64})\n"
    rb"# body-sha256: ([0-9a-f]{64})\n"
    rb"# corpus-sha256: ([0-9a-f]{64})\n"
    rb"# END REFUSAL PROTOCOL INTEGRITY\n"
)


class ArtifactIntegrityError(ValueError):
    pass


def verify_artifacts(module: bytes, corpus: bytes, *, source_digest: str) -> None:
    matches = list(_HEADER.finditer(module))
    if len(matches) != 1 or matches[0].start() != sum(len(line) for line in module.splitlines(keepends=True)[:2]):
        raise ArtifactIntegrityError("invalid refusal integrity header")
    header = matches[0]
    source, body, cases = (value.decode("ascii") for value in header.groups())
    if source != source_digest:
        raise ArtifactIntegrityError("refusal source digest mismatch")
    if hashlib.sha256(module[: header.start()] + module[header.end() :]).hexdigest() != body:
        raise ArtifactIntegrityError("refusal body digest mismatch")
    if hashlib.sha256(corpus).hexdigest() != cases:
        raise ArtifactIntegrityError("refusal corpus digest mismatch")
